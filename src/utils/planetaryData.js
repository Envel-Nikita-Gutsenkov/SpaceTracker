// Standard gravitational parameter μ = G·M of any catalogued body, in km^3/s^2, derived
// from its tabulated mass. Returns 0 for an unknown body. Used to keep each artificial
// orbiter's (periapsis, apoapsis, period) mutually consistent via Kepler's third law.
export function getBodyGM(bodyKey) {
  const massKg = PLANETARY_ELEMENTS_J2000[bodyKey]?.massKg;
  return massKg ? G_KM3_KG_S2 * massKg : 0;
}

